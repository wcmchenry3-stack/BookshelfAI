"""One-time developer tool: outline the logo wordmark's letters into `logo_glyphs.py`.

The logo's lettering is a set of glyph outlines (SVG path data), not live text, so the recipe and the
app need no font at run time and the output cannot change with an installed font. Run this only to
change the typeface or the wordmark; it rewrites `logo_glyphs.py`. Needs fontTools (requirements.txt).

The outlines come from Liberation Serif Regular (SIL Open Font License 1.1, (c) Red Hat, Inc.,
metric-compatible with Times New Roman). The notice is in docs/ASSETS.md.

Usage: python tools/assets/extract_logo_glyphs.py [path/to/LiberationSerif-Regular.ttf]
"""

from __future__ import annotations

import sys
from pathlib import Path

from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont

WORDMARK = "BookshelfAI"
DEFAULT_FONT = "/usr/share/fonts/truetype/liberation/LiberationSerif-Regular.ttf"
OUT = Path(__file__).with_name("logo_glyphs.py")


def _fmt(v: float) -> str:
    """Whole numbers stay whole; the half-unit midpoints of expanded curves keep one decimal."""
    return f"{v:.0f}" if v == int(v) else f"{v:.1f}"


def _expand_quadratics(start: tuple[float, float], pts: list[tuple[float, float]]) -> list[tuple[float, float, float, float]]:
    """A TrueType chain of off-curve points (the last is on-curve) as plain SVG quadratics.

    TrueType leaves out the on-curve point between two off-curve neighbours: it is their midpoint.
    SVG needs each (control, end) pair spelled out, so insert those midpoints here.
    """
    out = []
    offs, end = pts[:-1], pts[-1]
    for i, c in enumerate(offs):
        to = end if i == len(offs) - 1 else ((c[0] + offs[i + 1][0]) / 2, (c[1] + offs[i + 1][1]) / 2)
        out.append((c[0], c[1], to[0], to[1]))
    return out


def glyph_path(font: TTFont, ch: str) -> tuple[str, int]:
    """Path data (font units, y up, quadratic) and advance width of one character."""
    gs = font.getGlyphSet()
    name = font.getBestCmap()[ord(ch)]
    pen = DecomposingRecordingPen(gs)
    gs[name].draw(pen)
    d = []
    for op, pts in pen.value:
        if op == "moveTo":
            d.append("M" + " ".join(_fmt(c) for c in pts[0]))
        elif op == "lineTo":
            d.append("L" + " ".join(_fmt(c) for c in pts[0]))
        elif op == "qCurveTo":
            d.append("Q" + " ".join(_fmt(c) for seg in _expand_quadratics(None, list(pts)) for c in seg))
        elif op == "curveTo":
            d.append("C" + " ".join(_fmt(c) for p in pts for c in p))
        elif op in ("closePath", "endPath"):
            d.append("Z")
    return "".join(d), gs[name].width


def main(argv: list[str]) -> int:
    font = TTFont(argv[1] if len(argv) > 1 else DEFAULT_FONT)
    upm = font["head"].unitsPerEm
    lines = [
        '"""Outlined letters of the logo wordmark. GENERATED by extract_logo_glyphs.py; do not edit.',
        "",
        f"Liberation Serif Regular, SIL OFL 1.1. Path data in font units ({upm} per em), y up.",
        '"""',
        "",
        f"UNITS_PER_EM = {upm}",
        f'WORDMARK = "{WORDMARK}"',
        "GLYPHS: dict[str, tuple[str, int]] = {",
    ]
    for ch in sorted(set(WORDMARK)):
        d, adv = glyph_path(font, ch)
        lines.append(f'    "{ch}": ("{d}", {adv}),')
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
