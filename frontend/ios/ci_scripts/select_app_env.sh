#!/bin/bash
# Points Xcode Cloud builds of non-release branches at the dev backend (#973).
#
# An Xcode Cloud archive always builds the Release configuration, so the
# "Bundle React Native code" phase runs Expo with NODE_ENV=production and loads
# the committed frontend/.env.production (prod API, EXPO_PUBLIC_ENVIRONMENT=production).
# EXPO_PUBLIC_* values are inlined into the JS bundle, so without this script a
# TestFlight build from `dev` talks to the production API.
#
# Release builds (branch `main`, a PR into `main`, or a tag) keep .env.production.
# Every other build gets a gitignored .env.production.local, which Expo loads
# with higher precedence than .env.production, overriding only the values below.
# Called by ci_post_clone.sh before npm ci.
#
# Usage: select_app_env.sh <path to frontend/>
# Env:   CI_BRANCH, CI_PULL_REQUEST_TARGET_BRANCH, CI_TAG (set by Xcode Cloud).
# Bash 3.2 compatible (macOS /bin/bash).

set -eu

DEV_API_URL="https://bookshelfapi-dev.buffingchi.com"

frontend_dir="${1:?usage: select_app_env.sh <frontend dir>}"
local_env="$frontend_dir/.env.production.local"

if [ ! -d "$frontend_dir" ]; then
  echo "ERROR: frontend directory not found: $frontend_dir" >&2
  exit 1
fi

branch="${CI_BRANCH:-}"
pr_target="${CI_PULL_REQUEST_TARGET_BRANCH:-}"
tag="${CI_TAG:-}"

# Never let a stale override leak into a release build.
rm -f "$local_env"

if [ -n "$tag" ] || [ "$branch" = "main" ] || [ "$pr_target" = "main" ]; then
  echo "INFO: release build (branch='${branch}' pr_target='${pr_target}' tag='${tag}') → using .env.production (prod API)"
  exit 0
fi

cat > "$local_env" <<EOF
# Generated by ios/ci_scripts/select_app_env.sh (#973). Do not commit.
EXPO_PUBLIC_API_URL=$DEV_API_URL
EXPO_PUBLIC_ENVIRONMENT=development
EOF

echo "INFO: non-release build (branch='${branch}' pr_target='${pr_target}') → wrote .env.production.local (API: $DEV_API_URL, environment: development)"
