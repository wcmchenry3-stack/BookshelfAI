# Rollup and retention
# ---------------------------------------------------------------------------


def _utc_day(ts: datetime) -> date:
    return ts.astimezone(UTC).date()


async def _rollup_batch(db: AsyncSession, cutoff: datetime) -> int:
    """Move one batch of raw rows older than ``cutoff`` into the daily table;
    return how many raw rows were moved. One transaction."""
    oldest = (
        select(AIUsage.id)
        .where(AIUsage.created_at < cutoff)
        .order_by(AIUsage.id)
        .limit(PURGE_BATCH_SIZE)
    )
    moved = (
        await db.execute(
            delete(AIUsage)
            .where(AIUsage.id.in_(oldest))
            .returning(
                AIUsage.created_at,
                AIUsage.feature,
                AIUsage.model,
                AIUsage.status,
                AIUsage.input_tokens,
                AIUsage.output_tokens,
                AIUsage.cost_micros,
            )
        )
    ).all()
    if not moved:
        await db.commit()
        return 0

    totals: dict[tuple[date, str, str, str], list[int]] = defaultdict(
        lambda: [0, 0, 0, 0]
    )
    for created_at, feature, model, status, inp, out, cost in moved:
        t = totals[(_utc_day(created_at), feature, model, status)]
        t[0] += 1
        t[1] += inp
        t[2] += out
        t[3] += cost

    stmt = insert(AIUsageDaily).values(
        [
            {
                "day": day,
                "feature": feature,
                "model": model,
                "status": status,
                "calls": calls,
                "input_tokens": inp,
                "output_tokens": out,
                "cost_micros": cost,
            }
            for (day, feature, model, status), (calls, inp, out, cost) in sorted(
                totals.items()
            )
        ]
    )
    stmt = stmt.on_conflict_do_update(
        index_elements=[
            AIUsageDaily.day,
            AIUsageDaily.feature,
            AIUsageDaily.model,
            AIUsageDaily.status,
        ],
        set_={
            "calls": AIUsageDaily.calls + stmt.excluded.calls,
            "input_tokens": AIUsageDaily.input_tokens + stmt.excluded.input_tokens,
            "output_tokens": AIUsageDaily.output_tokens + stmt.excluded.output_tokens,
            "cost_micros": AIUsageDaily.cost_micros + stmt.excluded.cost_micros,
        },
    )
    await db.execute(stmt)
    # The delete and the upsert commit together.
    await db.commit()
    return len(moved)


async def _purge_daily(db: AsyncSession, cutoff: date) -> int:
    total = 0
    for _ in range(PURGE_MAX_BATCHES):
        batch = (
            select(
                AIUsageDaily.day,
                AIUsageDaily.feature,
                AIUsageDaily.model,
                AIUsageDaily.status,
            )
            .where(AIUsageDaily.day < cutoff)
            .limit(PURGE_BATCH_SIZE)
        )
        result = await db.execute(
            delete(AIUsageDaily).where(
                tuple_(
                    AIUsageDaily.day,
                    AIUsageDaily.feature,
                    AIUsageDaily.model,
                    AIUsageDaily.status,
                ).in_(batch)
            )
        )
        await db.commit()
        deleted = result.rowcount or 0
        total += deleted
        if deleted < PURGE_BATCH_SIZE:
            break
    return total


def rollup_cutoffs(now: datetime) -> tuple[datetime, date]:
    """``(raw_cutoff, daily_cutoff)``: raw rows created before the first are
    rolled up; daily rows for days before the second are deleted."""
    now = now.astimezone(UTC)
    return (
        now - timedelta(days=RAW_RETENTION_DAYS),
        now.date() - timedelta(days=DAILY_RETENTION_DAYS),
    )


async def rollup_and_purge(
    db: AsyncSession, now: datetime | None = None
) -> tuple[int, int]:
    """Roll raw rows older than 30 days into ``ai_usage_daily`` (and delete
    them), then delete daily rows older than 400 days. Both in bounded
    batches (at most ``PURGE_MAX_BATCHES`` each per run). Idempotent.
    Returns ``(raw rows rolled up, daily rows deleted)``."""
    raw_cutoff, daily_cutoff = rollup_cutoffs(now or datetime.now(UTC))
    rolled = 0
    for _ in range(PURGE_MAX_BATCHES):
        moved = await _rollup_batch(db, raw_cutoff)
        rolled += moved
        if moved < PURGE_BATCH_SIZE:
            break
    purged = await _purge_daily(db, daily_cutoff)
    return rolled, purged
