"""The AI usage ledger: one row per paid provider call, rolled up after 30 days
(#530).

Writing
-------
:func:`usage_insert` builds the ``ai_usage`` insert for one call, priced from
``app.ai.prices`` at :data:`~app.ai.prices.CURRENT_PRICE_VERSION`. ``/scan``
hands it to ``quota.release`` so the row is committed in the same transaction
as the settle (the lease delete). :func:`record` writes a row on its own (for
callers with no lease, e.g. a repeat served from a scan record, #585).

A row holds counts, cost, the feature, model and status, the user id and the
server-generated request id. Never the prompt, the image, or the model's
output.

Statuses
--------
``ok`` / ``refused`` / ``truncated`` / ``malformed``: the provider answered
(its ``ProviderResult.outcome``; ``malformed``, #572: a billed reply with no
usable answer, refunded to the user, tokens and cost as billed). ``timeout``: the provider timed out (its own
HTTP timeout or the gateway deadline; refunded). ``refunded``: the provider
was unavailable or never reached (refunded). ``error``: anything else after
the reservation (the reservation is kept). ``cache_hit``: served from a cache,
``cost_micros`` always 0.

Rollup
------
:func:`rollup_and_purge` (daily cleanup task) moves raw rows older than 30
days into ``ai_usage_daily`` per (UTC day, feature, model, status), in bounded
batches. Each batch deletes its raw rows (``DELETE ... RETURNING``) and adds
their totals to the daily rows in ONE transaction, so a crash cannot count a
row twice or lose it, and two concurrent runs cannot both move the same row.
A second run finds nothing old enough left, so it changes nothing. Daily rows
are kept 400 days. The daily table has no user column and no cache-token
columns (``input_tokens`` there is the sum of the raw ``input_tokens``,
which exclude cached tokens; ``cost_micros`` includes everything).

This module never calls a provider.
"""

import logging
import uuid
from collections import defaultdict
from datetime import UTC, date, datetime, timedelta

from sqlalchemy import delete, select, tuple_
from sqlalchemy.dialects.postgresql import insert
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.sql import Insert

from app.ai.prices import CURRENT_PRICE_VERSION, cost_micros
from app.core.logging import request_id_var
from app.models.ai_usage import (
    STATUS_CACHE_HIT,
    USAGE_STATUSES,
    AIUsage,
    AIUsageDaily,
)

logger = logging.getLogger(__name__)

RAW_RETENTION_DAYS = 30
DAILY_RETENTION_DAYS = 400
# Same bounded-batch pattern as app.ai.quota's purge.
PURGE_BATCH_SIZE = 5_000
PURGE_MAX_BATCHES = 20

# request_id_var's value outside a request.
_NO_REQUEST_ID = "-"


def current_request_id() -> str | None:
    """The server-generated request id (X-Request-ID), or None outside a
    request. Never taken from the client."""
    rid = request_id_var.get()
    return None if not rid or rid == _NO_REQUEST_ID else rid[:64]


def usage_insert(
    *,
    call_id: uuid.UUID,
    user_id: uuid.UUID | None,
    feature: str,
    model: str,
    status: str,
    input_tokens: int = 0,
    output_tokens: int = 0,
    cache_read_tokens: int = 0,
    cache_write_tokens: int = 0,
    request_id: str | None = None,
    price_version: str = CURRENT_PRICE_VERSION,
) -> Insert:
    """The ``ai_usage`` insert for one call, with its cost computed.

    ``call_id`` is generated by the server once per provider call. The insert
    is ``ON CONFLICT (call_id) DO NOTHING RETURNING call_id``, so executing it
    again (a settle retried after a commit whose acknowledgement was lost)
    adds no row and returns nothing.

    Raises ``ValueError`` for an unknown status or a bad token count and
    ``UnknownPriceError`` for a model with no price at ``price_version``.
    """
    if status not in USAGE_STATUSES:
        raise ValueError(f"unknown usage status {status!r}")
    if status == STATUS_CACHE_HIT:
        cost = 0  # nothing was billed; never price (the model may be retired)
    else:
        cost = cost_micros(
            model,
            price_version,
            input_tokens=input_tokens,
            output_tokens=output_tokens,
            cache_read_tokens=cache_read_tokens,
            cache_write_tokens=cache_write_tokens,
        )
    return (
        insert(AIUsage)
        .values(
            call_id=call_id,
            user_id=user_id,
            feature=feature,
            model=model,
            price_version=price_version,
            input_tokens=input_tokens,
            output_tokens=output_tokens,
            cache_read_tokens=cache_read_tokens,
            cache_write_tokens=cache_write_tokens,
            cost_micros=cost,
            status=status,
            request_id=request_id,
        )
        .on_conflict_do_nothing(index_elements=[AIUsage.call_id])
        # A row back means this execution inserted it; none means an earlier
        # execution already committed it (quota.release uses this so a
        # retried settle does not add the spend twice, #531).
        .returning(AIUsage.call_id)
    )


async def record(db: AsyncSession, **fields) -> None:
    """Insert one ledger row (:func:`usage_insert` arguments) and COMMIT.

    Warning: this commits the session on its own. It is only for paths with
    no settle to share a transaction with (e.g. repeats served from a scan record, #585). A paid
    provider call must hand :func:`usage_insert`'s statement to
    ``quota.release`` instead, so the row commits with the lease release.
    A ``call_id`` is generated when none is given.
    """
    if fields.get("call_id") is None:
        fields["call_id"] = uuid.uuid4()
    await db.execute(usage_insert(**fields))
    await db.commit()


