"""Integration tests for bookshelf_app default privileges (#696).

Verifies that a table created *after* migration 0028 automatically inherits
SELECT / INSERT / UPDATE / DELETE for ``bookshelf_app`` (and nothing more),
and a new sequence ``USAGE``, via the default privileges the migration sets
on the migrating role.

On a database built by ``alembic upgrade head`` a missing role or missing
default privileges FAIL this test; it never skips for them. Everything runs
in a rolled-back transaction, so no persistent changes are made.
"""

import pytest
import sqlalchemy as sa

from app.core.database import APP_DB_ROLE
from tests.integration.test_db_role import run_rolled_back

pytestmark = pytest.mark.integration

_PROBE_TABLE = "default_privileges_probe_0028"


def _has(connection, function: str, obj: str, privilege: str) -> bool:
    return bool(
        connection.execute(
            sa.text(f"SELECT {function}(:r, :o, :p)"),
            {"r": APP_DB_ROLE, "o": f"public.{obj}", "p": privilege},
        ).scalar_one()
    )


def _default_acl(connection, objtype: str) -> set[str]:
    """Privileges the migrating role's default ACL in public grants the app role."""
    return set(
        connection.execute(
            sa.text(
                "SELECT a.privilege_type "
                "FROM pg_default_acl d, aclexplode(d.defaclacl) a "
                "WHERE d.defaclrole = current_user::regrole "
                "AND d.defaclnamespace = 'public'::regnamespace "
                "AND d.defaclobjtype::text = :t "
                "AND a.grantee::regrole::text = :role"
            ),
            {"t": objtype, "role": APP_DB_ROLE},
        )
        .scalars()
        .all()
    )


def _check_new_objects_get_grants(connection) -> None:
    assert connection.execute(
        sa.text("SELECT 1 FROM pg_roles WHERE rolname = :r"), {"r": APP_DB_ROLE}
    ).scalar(), f"role {APP_DB_ROLE!r} does not exist on a migrated database"

    # Set by migration 0028 for the role that ran it (this connection's role).
    assert _default_acl(connection, "r") == {"SELECT", "INSERT", "UPDATE", "DELETE"}
    assert _default_acl(connection, "S") == {"USAGE"}

    connection.execute(
        sa.text(
            f"CREATE TABLE public.{_PROBE_TABLE} "
            "(id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)"
        )
    )
    sequence = connection.execute(
        sa.text("SELECT pg_get_serial_sequence(:t, 'id')"),
        {"t": f"public.{_PROBE_TABLE}"},
    ).scalar_one()
    sequence = sequence.split(".", 1)[1]

    for privilege in ("SELECT", "INSERT", "UPDATE", "DELETE"):
        assert _has(
            connection, "has_table_privilege", _PROBE_TABLE, privilege
        ), f"{privilege} on a new table is not granted to {APP_DB_ROLE}"
    for privilege in ("TRUNCATE", "REFERENCES", "TRIGGER"):
        assert not _has(
            connection, "has_table_privilege", _PROBE_TABLE, privilege
        ), f"{privilege} on a new table is granted to {APP_DB_ROLE}"
    assert _has(connection, "has_sequence_privilege", sequence, "USAGE")
    assert not _has(connection, "has_sequence_privilege", sequence, "UPDATE")


async def test_new_table_inherits_dml_grants():
    """A table created after 0028 automatically gets DML grants for bookshelf_app."""
    await run_rolled_back(_check_new_objects_get_grants)
